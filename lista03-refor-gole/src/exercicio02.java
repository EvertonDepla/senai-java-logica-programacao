
public class exercicio02 {

//2) Escreva um algoritmo que mostre os números de 30 até 15, em ordem decrescente.
	
	public static void main(String[] args) {
		
		int numero = 30;
		int repete = 0;
		
		while(repete <=15) {
			System.out.println(numero);
			numero = numero-1;
			repete++;
			
		}

	}

}
