
public class exercicio03 {

	//3) Escreva um algoritmo que mostre os 15 primeiros números inteiros maiores que 200.
	
	public static void main(String[] args) {
		
		int numero = 200;
		int repete = 0;
		
		while(repete <= 15) {
			
			numero = numero + 1;
			System.out.println(numero);
			repete++;
		}
		
	}

}
