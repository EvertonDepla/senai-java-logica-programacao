public class exercicio01 {

	//1) Escreva um algoritmo que mostre os números de 5 até 20, em ordem crescente.
	
	public static void main(String[] args) {
		
		int numero = 4;
		int repetir = 0;
		
		while (repetir <=15) {
			
			numero = numero + 1;
			repetir++;
			System.out.println(numero);
		}
		
		
	}

}
